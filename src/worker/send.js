// Dry-run is lenient (unsigned preview mail). In real mode a configured signature that cannot be
// read must stop the send: throws an error classified as a retryable pre-send failure (ENOENT/EACCES).
export function loadSignature(config) {
  if (!config?.signaturePath) return "";
  try {
    return readFileSync(config.signaturePath, "utf8");
  } catch (err) {
    if (config.dryRun) return "";
    throw Object.assign(new Error("signature file unreadable"), { code: err?.code === "EACCES" ? "EACCES" : "ENOENT" });
  }
}

// Per-tick, in-memory cache of resume bytes keyed by storage key + generation, so 100 mails cost one
// download. Concurrent requests share the promise; a failed fetch is not cached. Bounded: PDFs are <= 5 MB.
export function createResumeCache(max = 4) {
  const entries = new Map();
  return {
    get(key, generation, fetch) {
      const id = `${key}@${generation}`;
      if (entries.has(id)) return entries.get(id);
      const p = Promise.resolve()
        .then(fetch)
        .catch((err) => {
          entries.delete(id);
          throw err;
        });
      entries.set(id, p);
      if (entries.size > max) entries.delete(entries.keys().next().value);
      return p;
    },
  };
}

// A hung download must become a hold, not an in-flight send that goes stale.
function withDeadline(promise, ms) {
  let timer;
  const deadline = new Promise((_, reject) => {
    timer = setTimeout(() => reject(Object.assign(new Error("fetch timed out"), { reason: "unavailable" })), ms);
  });
  return Promise.race([promise, deadline]).finally(() => clearTimeout(timer));
}

const REASON_TEXT = { not_found: "not found", permission: "access refused", unavailable: "storage unavailable", invalid: "invalid key" };

// Real-mode pre-send step: the bytes of the resume this message was scheduled with, as a true MIME
// attachment. Anything that goes wrong throws an error classified as a HOLD (code ERESUME for the
// library, ENOENT/EACCES for the legacy file): the message is never sent without its resume. The
// messages never carry keys, paths, bucket names or credentials.
//   message.resume_id set -> that library resume at the stored generation (dry-run: skipped, no fetch)
//   otherwise             -> the legacy RESUME_PATH file, if configured (dry-run: lenient, like the signature)
export async function loadAttachments({ config, message, db, storage, cache, timeoutMs = 30_000 }) {
  if (message.resume_id) {
    if (config.dryRun) return [];
    let row;
    try {
      row = (await db.query("SELECT display_name, file_name, storage_key FROM resumes WHERE id = $1", [message.resume_id])).rows[0];
    } catch {
      throw Object.assign(new Error("resume could not be looked up"), { code: "ERESUME" });
    }
    const label = row ? `resume "${String(row.display_name).replace(/[\p{Cc}]/gu, " ").slice(0, 80)}"` : "the selected resume";
    if (!row) throw Object.assign(new Error(`${label} no longer exists`), { code: "ERESUME", reason: "not_found" });
    try {
      const content = await cache.get(row.storage_key, message.resume_generation, () => withDeadline(storage.get(row.storage_key, message.resume_generation), timeoutMs));
      if (!Buffer.isBuffer(content) || content.length === 0) throw new Error("empty");
      return [{ filename: row.file_name, content, contentType: "application/pdf" }];
    } catch (err) {
      const reason = typeof err?.reason === "string" && err.reason in REASON_TEXT ? err.reason : "unavailable";
      throw Object.assign(new Error(`${label} could not be fetched (${REASON_TEXT[reason]})`), { code: "ERESUME", reason });
    }
  }
  if (!config?.resumePath) return [];
  try {
    const content = readFileSync(config.resumePath);
    const ext = path.extname(config.resumePath).toLowerCase();
    return [{ filename: path.basename(config.resumePath), content, ...(ext === ".pdf" ? { contentType: "application/pdf" } : {}) }];
  } catch (err) {
    if (config.dryRun) return [];
    throw Object.assign(new Error("resume file unreadable"), { code: err?.code === "EACCES" ? "EACCES" : "ENOENT" });
  }
}

// RFC 5322 Message-ID, generated by us (and stored) before the SMTP call; nodemailer uses it verbatim.
export function newMessageId(config) {
  const domain = String(config?.gmailUser ?? "").split("@")[1];
  return `<${randomUUID()}@${/^[A-Za-z0-9.-]+$/.test(domain ?? "") ? domain : "mail-autosender.local"}>`;
}

// contact/message are DB rows. For follow-ups, `initialMessageId` threads the mail
// (In-Reply-To + References) and `template` is the stored follow-up template.
export function buildMail({ config, signatureHtml, contact, message, initialMessageId, template, attachments = [] }) {
  const mailConfig = {
    gmailUser: config.gmailUser,
    fromName: config.fromName,
    signatureHtml, // the attachment is added below from `attachments`, never from a path
  };
  let options;
  if (message.kind === "initial") {
    options = buildInitialMailOptions(mailConfig, { email: contact.email, subject: contact.subject, mailText: contact.mail_text });
  } else {
    const rendered = renderFollowup(
      { person: contact.person, role: contact.role, company: contact.company, subject: contact.subject, followupText: contact.followup_text },
      template,
    );
    options = buildFollowUpMailOptions(mailConfig, {
      email: contact.email,
      subject: contact.subject,
      followUpText: rendered.text,
      messageId: initialMessageId,
    });
    // Exactly one "Re: " prefix, even when the original subject or the template already carries some.
    options.subject = `Re: ${rendered.subject.replace(/^\s*(re:\s*)+/i, "")}`;
  }
  if (attachments.length) options.attachments = attachments;
  options.messageId = message.message_id;
  return options;
}
